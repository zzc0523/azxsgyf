FONT = "Microsoft YaHei"

def set_cjk(run, size=None, bold=None, color=None):
    run.font.name = FONT
    r = run._element; rPr = r.get_or_add_rPr()
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = OxmlElement('w:rFonts'); rPr.append(rFonts)
    rFonts.set(qn('w:eastAsia'), FONT)
    if size is not None: run.font.size = Pt(size)
    if bold is not None: run.font.bold = bold
    if color is not None: run.font.color.rgb = color

def shade(cell, fill):
    tcPr = cell._tc.get_or_add_tcPr()
    sh = OxmlElement('w:shd'); sh.set(qn('w:val'),'clear'); sh.set(qn('w:color'),'auto'); sh.set(qn('w:fill'),fill)
    tcPr.append(sh)

def add_table(doc, headers, rows, widths=None, header_fill="2F5496"):
    t = doc.add_table(rows=1, cols=len(headers)); t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i, h in enumerate(headers):
        hdr[i].text = ""; p = hdr[i].paragraphs[0]; run = p.add_run(h)
        set_cjk(run, 10, True, RGBColor(0xFF,0xFF,0xFF)); shade(hdr[i], header_fill)
    for r in rows:
        cells = t.add_row().cells
        for i, val in enumerate(r):
            cells[i].text = ""; p = cells[i].paragraphs[0]; run = p.add_run(str(val)); set_cjk(run, 9.5)
    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    return t

def btns_of(file):
    d = EXTRACT.get(file, {}); rows = []
    for t, oc in d.get("btns", []):
        if t and t.strip(): rows.append((t.strip(), oc.strip() if oc else "跳转/提交"))
    for t, oc in d.get("onclicks", []):
        if t and t.strip() and oc and oc.strip(): rows.append((t.strip(), oc.strip()))
    seen = set(); uniq = []
    for r in rows:
        if r not in seen: seen.add(r); uniq.append(r)
    return uniq

