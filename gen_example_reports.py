def TD(x, cls='', span=None, style=''):
    a = ''
    if cls: a += ' class="%s"' % cls
    if span: a += ' colspan="%d"' % span
    if style: a += ' style="%s"' % style
    return '<td%s>%s</td>' % (a, x)

def THS(cells):
    return '<tr>' + ''.join('<th>%s</th>' % c for c in cells) + '</tr>'

def TR(cells):
    return '<tr>' + ''.join(cells) + '</tr>'

def table(rows, cls=''):
    return '<table%s>%s</table>' % ((' class="%s"' % cls) if cls else '', ''.join(rows))

# —— 表格行辅助 ——
def kv4(l1, v1, l2, v2, red=()):
    return TR([TD(l1, 'lb red' if l1 in red else 'lb'), TD(v1),
               TD(l2, 'lb red' if l2 in red else 'lb'), TD(v2)])

def kv2(l, v):
    return TR([TD(l, 'lb'), TD(v)])

def fv(l, v, red=False):
    return TR([TD(l, ('lb red' if red else 'lb')), TD(v, span=3)])

def box4(label, content='', h=90):
    return TR([TD(label, 'boxlb', span=4)]) + TR([TD(content, 'boxc', span=4, style='height:%dpx' % h)])

def box2(label, content='', h=90):
    return TR([TD(label, 'boxlb', span=2)]) + TR([TD(content, 'boxc', span=2, style='height:%dpx' % h)])

def photos(n):
    return ''.join('<span class="ph">图片 %d</span>' % (i + 1) for i in range(n))

